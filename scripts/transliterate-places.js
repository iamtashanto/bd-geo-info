// Fills empty bn_name in src/data/bd-places.json with a rule-based Latin -> Bangla transliteration.
// Names already written by hand are never touched. Word-level dictionary comes from the official
// union/upazila/district Bangla names, so those spellings win over the rules.
// Usage: node scripts/transliterate-places.js
const fs = require('fs');
const path = require('path');
const data = (f) => JSON.parse(fs.readFileSync(path.join(__dirname, '../src/data', f), 'utf8'));
const placesPath = path.join(__dirname, '../src/data/bd-places.json');
const places = JSON.parse(fs.readFileSync(placesPath, 'utf8'));

const norm = (w) => w.toLowerCase().replace(/[^a-z]/g, '');
const dict = {};
const learn = (en, bn) => {
  const e = en.trim().split(/\s+/), b = (bn || '').trim().split(/\s+/);
  if (e.length === b.length) e.forEach((w, i) => { const k = norm(w); if (k && !dict[k]) dict[k] = b[i]; });
};
for (const list of Object.values(data('unions.json'))) list.forEach((u) => learn(u.name, u.bn_name));
for (const list of Object.values(data('bd-upazilas.json'))) list.forEach((u) => learn(u.name, u.bn_name));
const dd = data('bd-districts.json');
for (const d of Array.isArray(dd) ? dd : Object.values(dd).flat()) learn(d.name, d.bn_name);
Object.assign(dict, {
  pur: 'পুর', nagar: 'নগর', para: 'পাড়া', bari: 'বাড়ি', gaon: 'গাঁও', gram: 'গ্রাম', char: 'চর', kandi: 'কান্দি',
  ganj: 'গঞ্জ', hat: 'হাট', bazar: 'বাজার', bazaar: 'বাজার', north: 'উত্তর', south: 'দক্ষিণ', east: 'পূর্ব', west: 'পশ্চিম',
  uttar: 'উত্তর', dakshin: 'দক্ষিণ', purba: 'পূর্ব', paschim: 'পশ্চিম', madhya: 'মধ্য', middle: 'মধ্য', upper: 'উপর', lower: 'নিচ',
  bara: 'বড়', chhota: 'ছোট', choto: 'ছোট', new: 'নতুন', old: 'পুরাতন', hati: 'হাতি', ghat: 'ঘাট', dighi: 'দিঘী', pukur: 'পুকুর',
  island: 'দ্বীপ', beach: 'সৈকত', khali: 'খালী', danga: 'ডাঙ্গা', tola: 'তলা', mohal: 'মহল', mahalla: 'মহল্লা', basti: 'বস্তি',
  chak: 'চক', digar: 'দিগর', kot: 'কোট', kata: 'কাটা', mari: 'মারী', dia: 'দিয়া', diya: 'দিয়া', sadar: 'সদর', bazer: 'বাজার',
});

const cons = [['chh','ছ'],['ksh','ক্ষ'],['kh','খ'],['gh','ঘ'],['ch','চ'],['jh','ঝ'],['th','থ'],['dh','ধ'],['bh','ভ'],['ph','ফ'],['sh','শ'],['ng','ং'],
  ['rh','ড়'],['k','ক'],['g','গ'],['c','ক'],['j','জ'],['t','ত'],['d','দ'],['n','ন'],['p','প'],['f','ফ'],['b','ব'],['m','ম'],['y','য়'],['r','র'],['l','ল'],
  ['s','স'],['h','হ'],['w','ও'],['v','ভ'],['z','জ'],['q','ক'],['x','ক্স']];
const vow = { ind: { a:'আ', i:'ই', u:'উ', e:'এ', o:'ও', ai:'আই', au:'আউ', ee:'ঈ', oo:'ঊ', oi:'ওই', ou:'ঔ' },
  sign: { a:'া', i:'ি', u:'ু', e:'ে', o:'ো', ai:'াই', au:'াউ', ee:'ী', oo:'ূ', oi:'ৈ', ou:'ৌ' } };
const vowels = ['oi','ou','ai','au','ee','oo','a','i','u','e','o'];

function rules(word) {
  const w = word.toLowerCase();
  let out = '', i = 0, afterCons = false;
  while (i < w.length) {
    const v = vowels.find((x) => w.startsWith(x, i));
    if (v) {
      const atEnd = i + v.length === w.length;
      out += afterCons ? vow.sign[v] : vow.ind[v];
      afterCons = false; i += v.length; continue;
    }
    const c = cons.find(([k]) => w.startsWith(k, i));
    if (c) {
      const [k, b] = c;
      if (afterCons && b !== 'ং' && !/[হলক]$/.test(out) ) out += '্';
      out += b; afterCons = b !== 'ং'; i += k.length; continue;
    }
    i += 1;
  }
  return out.replace(/িআ$/, 'িয়া').replace(/িআ/g, 'িয়া');
}

const word = (w) => {
  const k = norm(w);
  if (dict[k]) return dict[k];
  // split known suffixes: Alampur -> Alam + pur
  for (const s of ['pur', 'nagar', 'para', 'bari', 'char', 'kandi', 'ganj', 'hat', 'bazar', 'ghat', 'dia', 'tola', 'danga', 'gaon', 'khali']) {
    if (k.length > s.length + 2 && k.endsWith(s)) return rules(k.slice(0, -s.length)) + dict[s];
  }
  return rules(k);
};
const convert = (name) => name.split(/\s+/).map((p) => (/[a-z]/i.test(p) ? word(p) : p)).join(' ');

let filled = 0;
for (const group of [places.byUpazila, places.byDistrict]) for (const rows of Object.values(group)) for (const r of rows) {
  if (!r[1]) { const bn = convert(r[0]); if (bn) { r[1] = bn; filled++; } }
}
places.attribution += ' Bangla names marked missing in the source were generated by transliteration (scripts/transliterate-places.js) and may differ from local spelling.';
fs.writeFileSync(placesPath, JSON.stringify(places));
console.log('filled', filled);
